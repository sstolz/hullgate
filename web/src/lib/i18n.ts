export type Key = keyof typeof en;

/** The string of `key`, with `{name}` placeholders filled from `vars`. */
export function t(key: Key, vars: Record<string, string> = {}): string {
  return en[key].replace(/\{(\w+)\}/g, (whole, name: string) => vars[name] ?? whole);
}

export function levelName(level: Level): string {
  return t(`level.${level}`);
}

/** The dictionary key naming an impact number the server sent, or null for an unknown one. */
export function impactKey(name: string): Key | null {
  const key = `impact.n.${name}`;
  return key in en ? (key as Key) : null;
}

/** A share reason of BR-079 in words; an unknown reason is shown as the server sent it. */
export function reasonText(reason: string): string {
  if (reason === 'other_client') return t('share.other_client');
  if (reason === 'sensitivity') return t('share.sensitivity');
  return reason;
}

/**
 * A closed code the server sent (a hiding reason, a reach reason, a class, a source, a pinned
 * state) in words, from the dictionary entry `<prefix>.<code>`; an unknown code is shown as the
 * server sent it. The screens show the code beside the words (BR-211).
 */
export function codeText(
  prefix: 'reason' | 'reach' | 'class' | 'source' | 'state' | 'undo',
  code: string,
): string {
  const key = `${prefix}.${code}`;
  return key in en ? t(key as Key) : code;
}
