"""BR-080 — `connection status` says what a connection is and where it serves, no secret (AC-09)."""

from __future__ import annotations

import json

from tests.support import REGISTRY, Gateway, standard_tree


def test_br_080_state_json_fields(gw: Gateway) -> None:
    standard_tree(gw)
    gw.service()
    gw.static("mpx/gitea-dev", "gd", "gitea-dev", "--account", "cairn-ai")
    gw.ok("connection", "place", "mpx/gitea-dev", "mpx/cairn/staging/dev")
    gw.ok("connection", "place", "mpx/gitea-dev", "mpx/cairn/prod/dev", "--confirm-share")
    [state] = json.loads(gw.ok("connection", "status", "--json"))
    assert state["name"] == "mpx/gitea-dev"
    assert state["service"] == "gitea-dev"
    assert state["account"] == "cairn-ai"
    assert state["scopes"] == []
    assert state["state"] == "active"
    assert state["key"] is None
    assert state["expires_at"] is None  # provided token: no known deadline
    assert state["placements"] == [
        {"role": "mpx/cairn/prod/dev", "sensitive": True},
        {"role": "mpx/cairn/staging/dev", "sensitive": False},
    ]
    text = gw.ok("connection", "status")
    assert text.splitlines()[0].startswith("mpx/gitea-dev   service gitea-dev   account cairn-ai")
    assert "  placed on mpx/cairn/prod/dev (sensitive)" in text
    assert "  placed on mpx/cairn/staging/dev (non-sensitive)" in text


def test_br_080_account_unknown_without_label(gw: Gateway) -> None:
    standard_tree(gw)
    gw.service()
    gw.static("mpx/gitea-dev", "gd")
    assert json.loads(gw.ok("connection", "status", "--json"))[0]["account"] == "unknown"


def test_br_080_no_secret_in_any_library_output(gw: Gateway) -> None:
    """Sweep of the output of every `service`, `application`, `connection` command of the
    tour: no value generated by the suite (in-memory registry of the fixture)."""
    standard_tree(gw)
    secret = "app-secret-" + "z" * 24
    REGISTRY.secrets.append(secret)
    outputs: list[str] = []

    def run(*args: str, stdin: str = "") -> None:
        result = gw.cli(*args, stdin=stdin)
        outputs.extend([result.out, result.err])

    run("service", "declare", "gitea-dev", "--server", "https://g.example.test")
    run("service", "list")
    run("service", "list", "--json")
    run("application", "declare", "app", "--service", "gitea-dev", "--mode", "declared",
        "--client-id", "cid", "--secret-file", "-", stdin=secret)  # fmt: skip
    run("application", "list")
    run("application", "list", "--json")
    value = gw.static("mpx/gitea-dev", "gd")
    run("connection", "add", "mpx/oauth", "--service", "gitea-dev", "--application", "app",
        "--prefix", "go")  # fmt: skip
    run("connection", "place", "mpx/gitea-dev", "mpx/cairn/staging/dev")
    run("connection", "status")
    run("connection", "status", "--json")
    run("connection", "list")
    run("connection", "list", "--json")
    run("connection", "reauthorize", "mpx/gitea-dev", "--file", "-", stdin=value + "-2\n")
    REGISTRY.secrets.append(value + "-2")
    run("export")
    run("audit", "tail", "-n", "100")
    run("connection", "remove", "mpx/gitea-dev", "--confirm", "mpx/gitea-dev")
    # Lot B: authorization, reauthorization, renewal, revocation, dynamic registration.
    provider = gw.provider("g")
    run("application", "declare", "dyn", "--service", "gitea-dev", "--mode", "dynamic")
    url = next(line for text in outputs for line in text.splitlines() if line.startswith("https"))
    callback = provider.approve(url)
    run("connection", "authorize", "mpx/oauth", "--callback", "-", stdin=callback)
    run("connection", "reauthorize", "mpx/oauth")
    run("connection", "renew", "mpx/oauth")
    run("connection", "status", "mpx/oauth", "--json")
    run("connection", "revoke", "mpx/oauth")
    run("service", "rediscover", "gitea-dev", "--confirm", "gitea-dev")
    run("application", "reregister", "dyn", "--confirm", "dyn")
    run("connection", "remove", "mpx/oauth", "--confirm", "mpx/oauth")
    assert provider.access_tokens
    assert provider.refresh_tokens
    blob = "\n".join(outputs)
    assert "mpx/gitea-dev" in blob
    for needle in {*REGISTRY.secrets, value, secret}:
        assert needle not in blob
