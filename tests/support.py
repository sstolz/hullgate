def grant(
    gw: Gateway,
    client: TestClient,
    path: str,
    client_id: str = CLIENT_ID,
    redirect: str = REDIRECT,
) -> dict[str, Any]:
    """Authorization and exchange: returns the JSON body of `/token`."""
    code, verifier = get_code(gw, client, path, client_id, redirect)
    response = exchange(client, path, code, verifier, client_id, redirect)
    assert response.status_code == 200, response.text
    body: dict[str, Any] = response.json()
    return body


