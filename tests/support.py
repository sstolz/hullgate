def ap(path: str) -> str:
    """Request path of a role's access point on the test client (F-014 §3.1)."""
    return f"/o/{org()}/p/{path}/mcp"


def oauth_path(path: str, action: str = "") -> str:
    """Request path of a role's authorization server, or of one of its actions."""
    return f"/o/{org()}/oauth/p/{path}" + (f"/{action}" if action else "")


class Clock:
    """Injected clock: starts from the real time, advances on demand."""

    def __init__(self) -> None:
        self.now = float(int(time.time()))

    def __call__(self) -> float:
        return self.now

    def advance(self, seconds: float) -> None:
        self.now += seconds


