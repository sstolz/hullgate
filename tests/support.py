def authorize_params(
    path: str,
    challenge: str,
    client_id: str = CLIENT_ID,
    redirect: str = REDIRECT,
    **extra: str,
) -> dict[str, str]:
    params = {
        "response_type": "code",
        "client_id": client_id,
        "redirect_uri": redirect,
        "scope": "mcp offline_access",
        "state": "st-" + secrets.token_hex(4),
        "code_challenge": challenge,
        "code_challenge_method": "S256",
        "resource": resource(path),
    }
    params.update(extra)
    return {k: v for k, v in params.items() if v != ""}


def start_authorization(client: TestClient, path: str, params: dict[str, str]) -> httpx.Response:
    return client.get(f"{oauth_path(path, 'authorize')}?{urlencode(params)}")


CONSENT_COOKIE = "hullgate_consent"


def request_id(response: httpx.Response) -> str:
    """Reference of the pending request, read in the /authorize cookie (never in the URL)."""
    assert response.headers["location"].endswith("/consent"), response.headers.get("location")
    for header in response.headers.get_list("set-cookie"):
        name, _, rest = header.partition("=")
        if name.strip() == CONSENT_COOKIE:
            value = rest.split(";", 1)[0]
            REGISTRY.secrets.append(value)
            return value
    raise AssertionError("request cookie absent")


def consent_page(client: TestClient, path: str, req: str) -> httpx.Response:
    return client.get(oauth_path(path, "consent"), headers={"Cookie": f"{CONSENT_COOKIE}={req}"})


def consent(
    gw: Gateway,
    client: TestClient,
    path: str,
    req: str,
    code: str | None = None,
    decision: str = "allow",
) -> httpx.Response:
    data = {"req": req, "decision": decision, "totp": gw.totp_code() if code is None else code}
    # m5: double submit, `req` field and request cookie
    return client.post(
        oauth_path(path, "consent"), data=data, headers={"Cookie": f"{CONSENT_COOKIE}={req}"}
    )


def code_from(response: httpx.Response) -> str:
    assert response.status_code == 302, response.text
    query = parse_qs(urlsplit(response.headers["location"]).query)
    assert "code" in query, query
    value = query["code"][0]
    REGISTRY.secrets.append(value)
    return value


def get_code(
    gw: Gateway,
    client: TestClient,
    path: str,
    client_id: str = CLIENT_ID,
    redirect: str = REDIRECT,
) -> tuple[str, str]:
    """Complete authorization (barrier included): returns (code, verifier)."""
    verifier, challenge = pkce()
    first = start_authorization(
        client, path, authorize_params(path, challenge, client_id, redirect)
    )
    assert first.status_code == 302, first.text
    return code_from(consent(gw, client, path, request_id(first))), verifier


def token_request(
    client: TestClient, path: str, form: dict[str, str | list[str]]
) -> httpx.Response:
    pairs: list[tuple[str, str]] = []
    for k, v in form.items():
        pairs += [(k, x) for x in (v if isinstance(v, list) else [v])]
    response = client.post(
        oauth_path(path, "token"),
        content=urlencode(pairs),
        headers={"Content-Type": "application/x-www-form-urlencoded"},
    )
    body = (
        response.json()
        if response.headers.get("content-type", "").startswith("application/json")
        else {}
    )
    for name in ("access_token", "refresh_token"):
        if isinstance(body, dict) and body.get(name):
            REGISTRY.secrets.append(body[name])
    return response


def exchange(
    client: TestClient,
    path: str,
    code: str,
    verifier: str,
    client_id: str = CLIENT_ID,
    redirect: str = REDIRECT,
    **extra: str | list[str],
) -> httpx.Response:
    form: dict[str, str | list[str]] = {
        "grant_type": "authorization_code",
        "code": code,
        "redirect_uri": redirect,
        "client_id": client_id,
        "code_verifier": verifier,
        "resource": resource(path),
    }
    form.update(extra)
    return token_request(client, path, form)


