def mcp(
    client: TestClient,
    path: str,
    token: str | None = None,
    method: str = "tools/list",
    params: dict[str, Any] | None = None,
    version: str = "2025-06-18",
    headers: dict[str, str] | None = None,
) -> Any:
    hdr = {"Accept": ACCEPT, "Content-Type": "application/json", "MCP-Protocol-Version": version}
    if token is not None:
        hdr["Authorization"] = f"Bearer {token}"
    hdr.update(headers or {})
    body: dict[str, Any] = {"jsonrpc": "2.0", "id": 1, "method": method}
    if params is not None:
        body["params"] = params
    return client.post(ap(path), headers=hdr, json=body)


def add_lineage(gw: Gateway, role_path: str, client_id: str = "client-test") -> str:
    """Active OAuth lineage placed on a role, written directly (the authorization server is
    lot B): used to check the reach of the revocations of BR-045 and BR-046."""
    conn = gw.connect()
    try:
        role = tree_mod.Tree.load(conn).resolve(role_path)
        now = int(gw.clock())
        conn.execute(
            "INSERT OR IGNORE INTO client (client_id, kind, node_id, created_at)"
            " VALUES (?, 'preregistered', 'org', ?)",
            (client_id, now),
        )
        count = conn.execute("SELECT count(*) FROM lineage").fetchone()[0]
        lineage_id = f"lin_{role.id}_{count}"
        conn.execute(
            "INSERT INTO lineage (id, role_id, client_id, resource, scope, created_at, expires_at)"
            " VALUES (?, ?, ?, ?, 'mcp', ?, ?)",
            (
                lineage_id,
                role.id,
                client_id,
                f"{PUBLIC_URL}/o/{gw.org_id}/p/{role_path}/mcp",
                now,
                now + 86400,
            ),
        )
        conn.execute(
            "INSERT INTO access_jti (jti, lineage_id, expires_at) VALUES (?, ?, ?)",
            (f"jti_{lineage_id}", lineage_id, now + 3600),
        )
        conn.commit()
    finally:
        conn.close()
    return lineage_id


def revoked_lineages(gw: Gateway) -> set[str]:
    conn = gw.connect()
    try:
        rows = conn.execute("SELECT id FROM lineage WHERE revoked = 1").fetchall()
        jti = conn.execute(
            "SELECT count(*) FROM access_jti a JOIN lineage l ON l.id = a.lineage_id"
            " WHERE l.revoked = 1 AND a.revoked = 0"
        ).fetchone()
    finally:
        conn.close()
    assert jti == (0,), "access token of a revoked lineage still valid"
    return {r[0] for r in rows}


_TEST_KEY: list[keys.SigningKey] = []


def shared_key() -> keys.SigningKey:
    """Throwaway signing key shared by the tests that build the listener themselves."""
    if not _TEST_KEY:
        import tempfile

        folder = Path(tempfile.mkdtemp(prefix="hullgate-key-"))
        keys.generate_signing_key(str(folder / "signing_key.pem"))
        _TEST_KEY.append(keys.SigningKey(str(folder / "signing_key.pem")))
    return _TEST_KEY[0]
