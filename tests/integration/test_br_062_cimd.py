def _fake_clock() -> list[float]:
    return [1000.0]


def test_br_062_document_reread_after_cache_redirect_removed(
    gw: Gateway, server: tuple[Docs, int, ssl.SSLContext]
) -> None:
    """B1 (review 411): second authorization after the document changed, cache expired."""
    docs, port, ctx = server
    standard_tree(gw)
    now = _fake_clock()
    gw.fetcher = Fetcher(
        context=ctx,
        resolve=lambda _h, _p: ["127.0.0.1"],
        allowed=lambda _a: True,
        clock=lambda: now[0],
    )
    cid = f"https://localhost:{port}/b1.json"
    other = "http://localhost:4567/autre"
    docs.routes["/b1.json"] = (200, _doc(cid), {}, 0.0)
    verifier, challenge = pkce()
    with gw.client() as client:
        first = start_authorization(client, ROLE, authorize_params(ROLE, challenge, cid))
        code = code_from(consent(gw, client, ROLE, request_id(first)))
        assert exchange(client, ROLE, code, verifier, client_id=cid).status_code == 200
        docs.routes["/b1.json"] = (200, _doc(cid, redirect_uris=[other]), {}, 0.0)
        cached = start_authorization(client, ROLE, authorize_params(ROLE, challenge, cid))
        assert cached.status_code == 302  # within 10 min: document cached
        hits = len(docs.hits)
        now[0] += 601  # cache expired
        old = start_authorization(client, ROLE, authorize_params(ROLE, challenge, cid))
        assert len(docs.hits) == hits + 1  # document read again, never the `client` table
        assert old.status_code == 400
        assert "location" not in old.headers
        new = start_authorization(
            client, ROLE, authorize_params(ROLE, challenge, cid, redirect=other)
        )
        assert new.headers["location"].endswith("/consent")


