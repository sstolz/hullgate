ROLE = "mpx/cairn/staging/dev"


class Docs:
    """Documents served by path: (status, body, headers, delay)."""

    def __init__(self) -> None:
        self.routes: dict[str, tuple[int, bytes, dict[str, str], float]] = {}
        self.hits: list[str] = []
        # dripping route: (complete raw response, delay per byte, header bytes dripped too)
        self.trickle: dict[str, tuple[bytes, float, bool]] = {}


def _cert(folder: Path) -> tuple[Path, Path]:
    key = ec.generate_private_key(ec.SECP256R1())
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "localhost")])
    now = datetime.datetime.now(datetime.UTC)
    cert = (
        x509.CertificateBuilder()
        .subject_name(name)
        .issuer_name(name)
        .public_key(key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - datetime.timedelta(minutes=5))
        .not_valid_after(now + datetime.timedelta(hours=1))
        .add_extension(
            x509.SubjectAlternativeName(
                [x509.DNSName("localhost"), x509.IPAddress(ipaddress.ip_address("127.0.0.1"))]
            ),
            critical=False,
        )
        .add_extension(x509.BasicConstraints(ca=True, path_length=None), critical=True)
        .sign(key, hashes.SHA256())
    )
    cert_path, key_path = folder / "cert.pem", folder / "key.pem"
    cert_path.write_bytes(cert.public_bytes(serialization.Encoding.PEM))
    key_path.write_bytes(
        key.private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption(),
        )
    )
    return cert_path, key_path


@pytest.fixture
def server(tmp_path: Path) -> Iterator[tuple[Docs, int, ssl.SSLContext]]:
    docs = Docs()
    cert_path, key_path = _cert(tmp_path)

    class Handler(BaseHTTPRequestHandler):
        def do_GET(self) -> None:
            docs.hits.append(self.path)
            if self.path in docs.trickle:
                raw, pause, slow_head = docs.trickle[self.path]
                head, _, body_part = raw.partition(b"\r\n\r\n")
                head += b"\r\n\r\n"
                if not slow_head:
                    self.wfile.write(head)
                    self.wfile.flush()
                for byte in (head + body_part) if slow_head else body_part:
                    try:
                        self.wfile.write(bytes([byte]))
                        self.wfile.flush()
                    except OSError:
                        return
                    time.sleep(pause)
                return
            status, body, headers, delay = docs.routes.get(self.path, (404, b"{}", {}, 0.0))
            time.sleep(delay)
            self.send_response(status)
            for k, v in {"Content-Type": "application/json", **headers}.items():
                self.send_header(k, v)
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def log_message(self, *_: object) -> None:
            return

    httpd = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    tls = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    tls.load_cert_chain(cert_path, key_path)
    httpd.socket = tls.wrap_socket(httpd.socket, server_side=True)
    thread = threading.Thread(target=httpd.serve_forever, daemon=True)
    thread.start()
    client_ctx = ssl.create_default_context(cafile=str(cert_path))
    try:
        yield docs, httpd.server_address[1], client_ctx
    finally:
        httpd.shutdown()
        httpd.server_close()


def _fetcher(ctx: ssl.SSLContext) -> Fetcher:
    return Fetcher(context=ctx, resolve=lambda _h, _p: ["127.0.0.1"], allowed=lambda _a: True)


def _doc(client_id: str, **extra: object) -> bytes:
    body: dict[str, object] = {
        "client_id": client_id,
        "redirect_uris": [REDIRECT],
        "client_name": "Client CIMD",
        **extra,
    }
    return json.dumps(body).encode()


def _authorize(gw: Gateway, client_id: str) -> tuple[int, str]:
    _, challenge = pkce()
    with gw.client() as client:
        r = start_authorization(client, ROLE, authorize_params(ROLE, challenge, client_id))
    return r.status_code, r.headers.get("location", "")


def test_br_062_valid_document_admits_the_client(
    gw: Gateway, server: tuple[Docs, int, ssl.SSLContext]
) -> None:
    docs, port, ctx = server
    standard_tree(gw)
    gw.fetcher = _fetcher(ctx)
    cid = f"https://localhost:{port}/client.json"
    docs.routes["/client.json"] = (200, _doc(cid), {}, 0.0)
    verifier, challenge = pkce()
    with gw.client() as client:
        first = start_authorization(client, ROLE, authorize_params(ROLE, challenge, cid))
        assert first.status_code == 302
        assert first.headers["location"].endswith("/consent")
        page = consent_page(client, ROLE, request_id(first))
        assert "Client CIMD" in page.text
        code = code_from(consent(gw, client, ROLE, request_id(first)))
        assert exchange(client, ROLE, code, verifier, client_id=cid).status_code == 200


