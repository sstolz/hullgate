MODES = {
    # keep-alive: the connection stays with http.client; `Connection: close` and HTTP/1.0:
    # http.client hands its socket to the response (`self.sock = None`), the case missed in
    # round 1 (review 413, B2).
    "keep-alive": b"HTTP/1.1 200 OK\r\n",
    "connection-close": b"HTTP/1.1 200 OK\r\nConnection: close\r\n",
    "http-1.0": b"HTTP/1.0 200 OK\r\n",
}


@pytest.mark.parametrize("slow_head", [False, True], ids=["dripped body", "dripped headers"])
@pytest.mark.parametrize("mode", sorted(MODES))
def test_br_062_hard_deadline_against_trickling_server(
    gw: Gateway,
    server: tuple[Docs, int, ssl.SSLContext],
    monkeypatch: pytest.MonkeyPatch,
    slow_head: bool,
    mode: str,
) -> None:
    """B2 (reviews 411, 413): hard deadline on the whole exchange, in every connection mode."""
    docs, port, ctx = server
    standard_tree(gw)
    gw.fetcher = _fetcher(ctx)
    monkeypatch.setattr(cimd, "TIMEOUT_S", 0.6)
    cid = f"https://localhost:{port}/slow-drip.json"
    body = _doc(cid)
    raw = (
        MODES[mode]
        + b"Content-Type: application/json\r\nContent-Length: "
        + str(len(body)).encode()
        + b"\r\n\r\n"
        + body
    )
    docs.trickle["/slow-drip.json"] = (raw, 0.1, slow_head)  # each read arrives in 0.1 s
    start = time.monotonic()
    status, location = _authorize(gw, cid)
    elapsed = time.monotonic() - start
    assert status == 400
    assert location == ""
    assert elapsed < 1.5, elapsed
    reasons = [e["reason"] for e in gw.audit() if e["action"] == "oauth.authorize"]
    assert reasons == ["cimd_timeout"]


@pytest.fixture
def stalling_tls() -> Iterator[int]:
    """TCP server that drips a TLS handshake that never completes."""
    import socket as sk

    listener = sk.socket()
    listener.bind(("127.0.0.1", 0))
    listener.listen(4)
    stop = threading.Event()

    def serve() -> None:
        listener.settimeout(0.2)
        while not stop.is_set():
            try:
                conn, _ = listener.accept()
            except OSError:
                continue
            with conn:
                # TLS "handshake" record announcing 16 KiB, then one byte / 0.1 s
                for byte in b"\x16\x03\x03\x40\x00" + b"\x00" * 200:
                    if stop.is_set():
                        break
                    try:
                        conn.sendall(bytes([byte]))
                    except OSError:
                        break
                    time.sleep(0.1)

    thread = threading.Thread(target=serve, daemon=True)
    thread.start()
    try:
        yield listener.getsockname()[1]
    finally:
        stop.set()
        listener.close()


