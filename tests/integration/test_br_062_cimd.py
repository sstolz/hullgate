def test_br_062_system_resolver_keeps_getaddrinfo_order(monkeypatch: pytest.MonkeyPatch) -> None:
    """Resolver order (RFC 6724) is preserved: IPv4 first here, with duplicates removed."""

    def fake(host: str, port: int, **_: object) -> list[tuple[object, ...]]:
        return [
            (10, 1, 6, "", ("192.0.2.6", port)),
            (10, 1, 6, "", ("2001:db8::6", port, 0, 0)),
            (2, 1, 6, "", ("192.0.2.6", port)),
        ]

    monkeypatch.setattr(socket, "getaddrinfo", fake)
    assert cimd.system_resolve("git.example.test", 443) == ["192.0.2.6", "2001:db8::6"]
