    assert fetcher.document(cid)["client_id"] == cid
    assert docs.hits == ["/client.json"]
    # all verified before connection, then each again before it is dialled
    assert tried == ["::1", "127.0.0.2", "127.0.0.1", "::1", "127.0.0.2", "127.0.0.1"]


