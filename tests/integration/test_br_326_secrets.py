ROOT = Path(__file__).resolve().parents[2]


def command(root: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        args,
        cwd=root,
        capture_output=True,
        text=True,
        check=False,
        env={k: v for k, v in os.environ.items() if not k.startswith("GIT_")},
    )


@pytest.fixture
def repo(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    for key in list(os.environ):
        if key.startswith("GIT_"):
            monkeypatch.delenv(key)
    (tmp_path / "scripts").mkdir()
    (tmp_path / "qa").mkdir()
    for name in ("secret_scanner.py", "qa_secrets.py", "qa_check.py", "qa_contract.py", "qa.py"):
        shutil.copyfile(ROOT / "scripts" / name, tmp_path / "scripts" / name)
    shutil.copyfile(ROOT / qa_secrets.PIN, tmp_path / qa_secrets.PIN)
    (tmp_path / qa_secrets.ALLOWLIST).write_text("[]\n")
    shutil.copyfile(ROOT / "Makefile", tmp_path / "Makefile")
    assert command(tmp_path, "git", "init", "-q").returncode == 0
    assert command(tmp_path, "git", "add", ".").returncode == 0
    return tmp_path


def token(letter: str = "A") -> str:
    # Construct synthetic detector fixtures; never usable credentials.
    return "gh" + "p_" + letter * 36


def scan(repo: Path) -> subprocess.CompletedProcess[str]:
    return command(repo, "make", "--no-print-directory", "qa", "QA_TOOLS=secrets:blocking")


def accept(repo: Path, value: str) -> None:
    (repo / qa_secrets.ALLOWLIST).write_text(
        json.dumps(
            [
                {
                    "path": "fixture.txt",
                    "detector": "github-token",
                    "fingerprint": hashlib.sha256(value.encode()).hexdigest()[:24],
                    "reason": "test dummy generated by the scanner regression test",
                }
            ]
        )
    )


def test_br_326_clean_then_planted_then_second_value_and_stale(repo: Path) -> None:
    assert "QA secrets blocking OK" in scan(repo).stdout
    (repo / "fixture.txt").write_text(token())
    command(repo, "git", "add", "fixture.txt")
    first = scan(repo)
    assert first.returncode != 0
    assert "QA secrets blocking FINDINGS" in first.stdout
    assert "QA: KO secrets" in first.stdout
    assert token() not in first.stdout + first.stderr
    accept(repo, token())
    assert "QA secrets blocking OK" in scan(repo).stdout
    (repo / "fixture.txt").write_text(token() + "\n" + token("B"))
    second = scan(repo)
    assert second.returncode != 0
    assert "FINDINGS" in second.stdout
    assert token("B") not in second.stdout + second.stderr
    (repo / "fixture.txt").write_text("gone")
    stale = scan(repo)
    assert stale.returncode != 0
    assert "stale allowlist" in stale.stdout


def test_br_326_tracks_binary_and_ignores_only_workshop(repo: Path) -> None:
    (repo / ".cairn/runs").mkdir(parents=True)
    (repo / ".cairn/runs/fixture").write_text(token())
