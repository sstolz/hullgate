def test_br_326_image_runtime_is_offline_and_read_only(
    repo: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    real_run = subprocess.run
    calls = []

    def run(args: list[str], **kwargs: object) -> subprocess.CompletedProcess[str]:
        if args[0] != "docker":
            # Only fixture Git enumeration reaches the real subprocess runner.
            return real_run(args, **kwargs)  # type: ignore[call-overload,no-any-return]
        calls.append(args)
        return subprocess.CompletedProcess(args, 0, "[]", "")

    monkeypatch.setattr(subprocess, "run", run)
    verdict, _, _ = qa_secrets.evaluate(repo, "image")
    assert verdict == "OK"
    assert len(calls) == 1
    assert {"--pull=never", "--network=none", "--read-only", "--cap-drop=ALL"} <= set(calls[0])
    assert qa_secrets.validate_pin(repo) in calls[0]


